def initialize_gigachat(task: str, LECTURE, question_count=10):
    '''
    Функция, которая инициализирует gigachat  для каких либо задач
    :param task: 'notes' или 'quiz' для конспетов или для квиза
    :param LECTURE: материал
    :return: сам клиент и чат с ним
    '''
    load_dotenv()
    GIGACHAT_TOKEN = os.getenv('GIGACHAT_TOKEN')

    client = GigaChat(
        base_url="https://api.giga.chat/v1",
        credentials=GIGACHAT_TOKEN,
        scope="GIGACHAT_API_PERS",
        verify_ssl_certs=False,
        timeout=300
    )

    if task == 'quiz':
        SYSTEM_PROMPT = get_quiz_prompt(
            question_count
        )

        response_format = {
            'type': 'json_schema',
            'schema': schema,
            'strict': True,
        }
    elif task == 'notes':
        SYSTEM_PROMPT = SYSTEM_PROMPT_FOR_NOTES
        response_format = None
    else:
        return 0

    messages = [
        Messages(role=MessagesRole.SYSTEM, content=SYSTEM_PROMPT),
        Messages(role=MessagesRole.USER, content=LECTURE)
    ]

    chat_params = {
        "model": "GigaChat-3-Ultra",
        "messages": messages
    }

    if response_format:
        chat_params["response_format"] = response_format

    chat = Chat(**chat_params)

    return client, chat


def response_gigachat(client, chat):
    '''
    Функция отправляет запрос в чат на тот клиент, который вы указали
    :param client: клиент
    :param chat: чат
    :return: ответ gigachat
    '''
    resp = client.chat(chat)
    raw = resp.choices[0].message.content
    return raw


